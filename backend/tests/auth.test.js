async function setup(t) {
  const db = openDatabase(':memory:'), auth = authService(db), imports = importService(db);
  const p = imports.preview(book([person('00000001'),person('00000002','00000001'),person('00000003','',{company:'Empresa B'})]),'test.xlsm');
  imports.confirm({token:p.token});
  const companies = db.prepare('SELECT * FROM companies ORDER BY name').all();
  const owner = await auth.create({username:'owner',displayName:'Creador',password},true);
  const server = createApp(db).listen(0,'127.0.0.1');
  await new Promise(resolve=>server.once('listening',resolve));
  const base = `http://127.0.0.1:${server.address().port}/api/v1`;
  async function request(path,{method='GET',body,cookie}={}) {
    const res = await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(cookie ? {Cookie:cookie} : {})},body:body===undefined ? undefined : JSON.stringify(body)});
    return {status:res.status,body:await res.json(),cookie:res.headers.get('set-cookie')?.split(';')[0],headers:res.headers};
  }
  const login = async (username,pass=password) => request('/auth/login',{method:'POST',body:{username,password:pass}});
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));db.close();});
  return {db,auth,imports,companies,owner,request,login};
}
test('usuarios: acceso inmediato al crear, restablecimiento y revocación inmediata',async t=>{
  const {auth,companies,owner,request,login} = await setup(t);
  const permission = {companyId:companies[0].id,module:'board'};
  const member = await auth.create({username:'worker',displayName:'Personal',password,permissions:[permission]});
  assert.equal(member.status,'APPROVED');
  const immediate = await login('worker');
  assert.equal(immediate.status,200);
  assert.equal(immediate.body.mustChangePassword,false);
  assert.equal((await request('/companies',{cookie:immediate.cookie})).status,200);
  assert.equal((await request('/companies')).status,401);
  await auth.resetPassword(member.id,password);
  const first = await login('worker');
  assert.equal(first.status,200);assert.equal(first.body.mustChangePassword,false);
  assert.ok(first.headers.get('set-cookie').includes('HttpOnly'));
  assert.ok(first.headers.get('set-cookie').includes('SameSite=Strict'));
  assert.equal((await request('/companies',{cookie:first.cookie})).status,200);
  assert.equal((await request('/auth/password',{method:'POST',cookie:first.cookie,body:{currentPassword:password,newPassword:'Nueva123'}})).status,403);
  assert.equal((await request('/companies',{cookie:first.cookie})).status,200);
  assert.equal((await login('worker','Nueva123')).status,401);
  const admin = await login('owner');
  assert.equal((await request('/auth/users/'+member.id,{method:'PUT',cookie:admin.cookie,body:{status:'APPROVED',permissions:[permission],password:'Nueva123'}})).status,200);
  assert.equal((await request('/companies',{cookie:first.cookie})).status,401);
  const session = await login('worker','Nueva123');
  assert.equal((await request('/auth/users',{cookie:session.cookie})).status,403);
  assert.equal((await request('/auth/users/'+owner.id,{method:'PUT',cookie:session.cookie,body:{status:'APPROVED',permissions:[]}})).status,403);
  await auth.update(member.id,{status:'DISABLED',permissions:[]});
  assert.equal((await request('/companies',{cookie:session.cookie})).status,401);
  assert.equal((await login('worker','Nueva123')).status,401);
});
