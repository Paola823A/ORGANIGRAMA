test('usuarios: edición y eliminación reservadas al creador; conserva personal e historial y revoca sesiones',async t=>{
  const {auth,companies,db,owner,request,login} = await setup(t);
  const employee = db.prepare('SELECT id FROM employees LIMIT 1').get();
  const permissions = [{companyId:companies[0].id,module:'board'}];
  const member = await auth.create({username:'editable',employeeId:employee.id,password,permissions});
  const memberCookie = (await login('editable')).cookie;
  assert.equal((await request('/auth/users/'+member.id,{method:'DELETE',cookie:memberCookie})).status,403);
  const ownerCookie = (await login('owner')).cookie;
  const changed = await request('/auth/users/'+member.id,{method:'PUT',cookie:ownerCookie,body:{username:'renamed',displayName:'Nombre actualizado',password:'Definitiva-mas-larga',status:'APPROVED',permissions}});
  assert.equal(changed.status,200);assert.equal(changed.body.username,'renamed');assert.equal(changed.body.displayName,'Nombre actualizado');
  assert.equal((await request('/companies',{cookie:memberCookie})).status,401);
  assert.equal((await login('editable')).status,401);
  assert.equal((await login('renamed')).status,401);
  const updatedLogin = await login('renamed','Definitiva-mas-larga');
  assert.equal(updatedLogin.status,200);assert.equal(updatedLogin.body.mustChangePassword,false);
  const fresh = updatedLogin.cookie;
  const bad = await request('/auth/users/'+member.id,{method:'PUT',cookie:ownerCookie,body:{status:'DISABLED',permissions:[],password:'12345'}});
  assert.equal(bad.status,400);
  assert.equal((await request('/companies',{cookie:fresh})).status,200);
  assert.equal((await request('/auth/users/'+member.id,{method:'PUT',cookie:ownerCookie,body:{status:'APPROVED',permissions,password:''}})).status,200);
  assert.equal((await login('renamed','Definitiva-mas-larga')).status,200);
  const batch = db.prepare('SELECT id FROM import_batches LIMIT 1').get();
  db.prepare('UPDATE import_batches SET actor_user_id=? WHERE id=?').run(member.id,batch.id);
  assert.equal((await request('/auth/users/'+owner.id,{method:'DELETE',cookie:ownerCookie})).status,400);
  assert.equal((await request('/auth/users/'+member.id,{method:'DELETE',cookie:ownerCookie})).status,200);
  assert.ok(!(await request('/auth/users',{cookie:ownerCookie})).body.some(u=>u.id===member.id));
  assert.equal((await request('/companies',{cookie:fresh})).status,401);
  assert.equal((await login('renamed')).status,401);
  assert.equal((await request('/auth/users/'+member.id,{method:'PUT',cookie:ownerCookie,body:{status:'APPROVED',permissions}})).status,400);
  assert.ok(db.prepare('SELECT 1 FROM employees WHERE id=?').get(employee.id));
  assert.equal(db.prepare('SELECT actor_user_id FROM import_batches WHERE id=?').get(batch.id).actor_user_id,member.id);
  assert.deepEqual(db.pragma('foreign_key_check'),[]);
});
